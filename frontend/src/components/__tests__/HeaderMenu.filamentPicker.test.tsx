import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { fireEvent, render, screen, within } from "@testing-library/react";

import { HeaderMenu } from "../HeaderMenu";
import { translations } from "../../i18n/translations";

function renderMenu() {
  return render(
    <HeaderMenu
      backendStatus="ok"
      reproTicketId={null}
      onReportBug={vi.fn()}
    />,
  );
}

describe("HeaderMenu filament-picker integration", () => {
  beforeEach(() => {
    vi.stubEnv("VITE_FP_INTEGRATION", "0");
    vi.stubEnv("VITE_FP_HIDE_LOCAL_ONLY", "0");
  });

  afterEach(() => {
    vi.unstubAllEnvs();
  });

  it("keeps the upstream menu unchanged when integration is disabled", () => {
    renderMenu();
    fireEvent.click(screen.getByTestId("header-menu-button"));

    expect(screen.queryByTestId("filament-picker-links")).not.toBeInTheDocument();
    expect(screen.getByRole("button", { name: "深色模式" })).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "新手引导" })).toBeInTheDocument();
  });

  it("shows all five configured links with their real routes when enabled", () => {
    vi.stubEnv("VITE_FP_INTEGRATION", "1");
    renderMenu();
    fireEvent.click(screen.getByTestId("header-menu-button"));

    const links = within(screen.getByTestId("filament-picker-links")).getAllByRole("link");
    expect(links).toHaveLength(5);
    expect(screen.getByRole("link", { name: "← 选色站" })).toHaveAttribute(
      "href",
      "https://filament.ibaozi.com/",
    );
    expect(screen.getByRole("link", { name: "色卡浏览" })).toHaveAttribute(
      "href",
      "https://filament.ibaozi.com/",
    );
    expect(screen.getByRole("link", { name: "图片配色" })).toHaveAttribute(
      "href",
      "https://filament.ibaozi.com/#/plan",
    );
    expect(screen.getByRole("link", { name: "打印成本" })).toHaveAttribute(
      "href",
      "https://filament.ibaozi.com/#/cost",
    );

    const source = screen.getByRole("link", { name: "源码" });
    expect(source).toHaveAttribute("href", "https://github.com/a523959108-rgb/filament-lumina");
    expect(source).toHaveAttribute("target", "_blank");
    expect(source).toHaveAttribute("rel", "noopener");
    expect(screen.getByText("基于 Lumina-Layers")).toBeInTheDocument();
  });

  it("keeps the bilingual public-credit download copy", () => {
    expect(translations.slicer_credit_hint).toEqual({
      zh: "公开分享或销售请标注由 Lumina-Layers 生成",
      en: "If you share or sell publicly, please credit: generated by Lumina-Layers",
    });
  });
});
